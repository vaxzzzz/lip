import java.util.Scanner;

public class exerciciovetores {
    public static void main(String[] args) {
        int[] numeros = {5, 10, 15, 20, 25};
        int soma = 0;

        for (int i = 0; i < numeros.length; i++) {
            soma += numeros[i]; 
        }

        System.out.println("A soma total é: " + soma);
    }
}





    
